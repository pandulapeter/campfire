/**
 * Archives written by real tools, as hex since a common test reads no resource files on every target (the module's
 * `DYNAMIC_STREAM` is kept the same way), so that the reader's ZIP64 rules follow what writers really write rather than
 * the format's letter. Each ZIP64 one sits beside its twin, the same content written without ZIP64, which it must read
 * as. Written on macOS on 2026-11-17 by Info-ZIP Zip 3.0 (Apple's build), `ditto`, Python 3.14.6's `zipfile`, and
 * OpenJDK 25.0.1's `java.util.zip.ZipOutputStream`; Go and 7-Zip were not installed, and Windows Explorer and OneDrive
 * cannot run here, so their layouts are built in the test from what the plan says of them, not from their files. The
 * generators stayed outside the repository.
 *
 * The small archives hold the same four files: `empty.txt` (0 bytes), `songs/amazing_grace.cho` (132 bytes of
 * ChordPro, deflated), `songs/noise.bin` (300 random bytes), and `songs/árvíztűrő.txt` (32 bytes, a UTF-8 name):
 *
 * - [INFO_ZIP] and [INFO_ZIP_ZIP64]: `zip -q -X out.zip <files>`, then with `-fz`. With ZIP64 forced, the end record
 *   gives the real entry count and directory size and only the directory offset at its marker, followed by a ZIP64
 *   record and locator (one disk); each central header has only the uncompressed size at its marker, its `0x0001` field
 *   holding just that; each local header has both sizes at their markers and both in its field.
 * - [INFO_ZIP_STREAMED] and [INFO_ZIP_ZIP64_STREAMED]: the same written to a pipe (`zip -q -X - <files> | cat`), so
 *   every entry is deflated and followed by a data descriptor (bit 3). With `-fz` the descriptors have 8-byte sizes
 *   and the end record has its directory offset at the marker, but **no ZIP64 record or locator is written at all**:
 *   the archive names a value only a ZIP64 record holds and has none. `unzip` lists it by guessing the offset from
 *   where the end record sits; Python's `zipfile` lists it the same way and then fails to read an entry. It is
 *   refused as damaged, as the in-memory reader refuses it.
 * - [PYTHON] and [PYTHON_ZIP64]: `ZipFile.open(info, "w", force_zip64=True)`, the `.cho` deflated and the rest stored.
 *   Python forces ZIP64 into the local headers only (both sizes at their markers, both in the field); the central
 *   directory and the end record are as without it, so both readers read it as they always have. `zipfile` writes no
 *   ZIP64 end records unless an archive needs them, whatever it is asked.
 * - `ZipOutputStream` writes no ZIP64 into an archive of small entries, deflated ones streamed (bit 3, 16-byte data
 *   descriptors with their signature), so it has no small fixture.
 *
 * Past 65,535 entries (70,000 one-to-five byte files, written but not kept, a few MB each): `zip -r`, `ditto -c -k`,
 * `zipfile`, and `ZipOutputStream` all write an end record whose two entry counts are at `0xFFFF` while its directory
 * size and offset are the real ones, then a 44-byte ZIP64 record (disks 0, the real count twice, the same size and
 * offset) and a locator saying one disk, and no `0x0001` field in any entry; `ditto` adds `__MACOSX/._*` entries of
 * extended attributes and, like Java, deflates every entry behind a data descriptor. The test builds such archives
 * rather than keeping them.
 *
 * Past 4 GiB (`a.cho`, a 4,600,000,000 byte `big.bin` of random bytes, `z.cho`): [DITTO_LARGE], [INFO_ZIP_LARGE],
 * [PYTHON_LARGE], and [JAVA_LARGE] keep each archive's first 160 bytes (the first local headers) and its last few
 * hundred (the last local headers and their data, the central directory, and the end records); the gigabytes between
 * are left out, so they are read through a [SparseZipSource]. Every one of them wrote ZIP64 records, `ditto` (which
 * writes what Archive Utility writes) included, so no tool on this Mac writes a wrapped archive. What they wrote:
 * - `ditto`: the end record's entry counts at `0xFFFF` and its offset at the marker, its directory size real; a ZIP64
 *   record and a locator saying one disk. `big.bin` has both sizes at their markers and both in its `0x0001` field,
 *   the later entries their offsets; every entry is deflated behind a data descriptor, `big.bin`'s with 8-byte sizes,
 *   and its local header has a `0x0001` field holding zeroes.
 * - Info-ZIP: the end record's offset at the marker and its counts and size real; `big.bin` deflated with both sizes
 *   in its field, `z.cho` with its offset in its field, `a.cho` (before 4 GiB) with no field.
 * - Python: as Info-ZIP's, `big.bin` stored.
 * - Java: as Info-ZIP's, every entry deflated behind a data descriptor (`big.bin`'s with 8-byte sizes), and local
 *   headers without a `0x0001` field, `big.bin`'s included.
 */

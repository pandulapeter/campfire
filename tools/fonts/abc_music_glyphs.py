"""
Writes the outlines of abc2svg's music font as SVG path data into `AbcMusicGlyphs.kt`, which draws the staff notation
abc2svg renders: abc2svg writes every music symbol as a character of that font, and the app draws it as a path rather
than handing a font to the platform's text engine, which would differ between Skia, Android, and a PDF.

Read from the font's FontForge source, `font/abc2svg.sfd` in abc2svg's repository at the release the app bundles
(https://chiselapp.com/user/moinejf/repository/abc2svg, file `font/abc2svg.sfd` at the tag, through the timeline's
"raw" link), so no font tooling is needed. The outlines stay under the font's SIL Open Font License, which the
generated file says.

    python3 -I tools/fonts/abc_music_glyphs.py path/to/abc2svg.sfd

Every glyph with a code point is written, keyed by it, with its advance width, both in font units (1024 to the em),
the y axis flipped to point down as SVG's does, so a glyph is drawn by scaling it by font size / 1024 and moving it to
its baseline point.
"""

